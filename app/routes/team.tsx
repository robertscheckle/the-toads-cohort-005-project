function getTeamForAdmin(userId: number) {
  const membership = db
    .select()
    .from(teamMembers)
    .where(
      and(
        eq(teamMembers.userId, userId),
        eq(teamMembers.role, TeamMemberRole.Admin)
      )
    )
    .get();

  if (!membership) return undefined;

  return db.select().from(teams).where(eq(teams.id, membership.teamId)).get();
}

function getCouponsForTeam(teamId: number) {
  return db.select().from(coupons).where(eq(coupons.teamId, teamId)).all();
}

function getCourseById(id: number) {
  return db.select().from(courses).where(eq(courses.id, id)).get();
}

function getUserById(id: number) {
  return db.select().from(users).where(eq(users.id, id)).get();
}

interface CourseStats {
  courseId: number;
  courseTitle: string;
  courseSlug: string;
  totalSeats: number;
  claimedSeats: number;
  /** Unclaimed Team Seats from a Refunded Purchase; left out of totalSeats. */
  unavailableSeats: number;
}

interface CouponRow {
  id: number;
  code: string;
  courseId: number;
  courseTitle: string;
  redeemedByEmail: string | null;
  /** Why an unclaimed Team Seat cannot be claimed right now, if it can't. */
  seatBlock: TeamSeatBlock | null;
  createdAt: string;
}

export function meta() {
  return [
    { title: "Team — Cadence" },
    { name: "description", content: "Manage your team's course seats" },
  ];
}

export async function loader({ request }: Route.LoaderArgs) {
  const currentUserId = await getCurrentUserId(request);

  if (!currentUserId) {
    throw data("Select a user from the DevUI panel.", { status: 401 });
  }

  const team = getTeamForAdmin(currentUserId);

  if (!team) {
    throw data("You don't have a team. Purchase team seats to create one.", {
      status: 403,
    });
  }

  const allCoupons = getCouponsForTeam(team.id);

  // A claimed seat stays claimed whatever happens to its Purchase; only
  // unclaimed ones are held or ended by a Refund Request.
  const blockByPurchase = new Map<number, TeamSeatBlock | null>();
  function seatBlockFor(coupon: (typeof allCoupons)[number]) {
    if (coupon.redeemedByUserId !== null) return null;
    if (!blockByPurchase.has(coupon.purchaseId)) {
      blockByPurchase.set(coupon.purchaseId, getTeamSeatBlock(coupon.purchaseId));
    }
    return blockByPurchase.get(coupon.purchaseId)!;
  }

  // Build per-course stats
  const courseMap = new Map<
    number,
    {
      courseId: number;
      courseTitle: string;
      courseSlug: string;
      total: number;
      claimed: number;
      unavailable: number;
    }
  >();

  for (const coupon of allCoupons) {
    if (!courseMap.has(coupon.courseId)) {
      const course = getCourseById(coupon.courseId);
      courseMap.set(coupon.courseId, {
        courseId: coupon.courseId,
        courseTitle: course?.title ?? "Unknown Course",
        courseSlug: course?.slug ?? "",
        total: 0,
        claimed: 0,
        unavailable: 0,
      });
    }
    const entry = courseMap.get(coupon.courseId)!;
    if (seatBlockFor(coupon) === "refunded") {
      entry.unavailable++;
      continue;
    }
    entry.total++;
    if (coupon.redeemedByUserId !== null) {
      entry.claimed++;
    }
  }

  const courseStats: CourseStats[] = Array.from(courseMap.values()).map(
    (e) => ({
      courseId: e.courseId,
      courseTitle: e.courseTitle,
      courseSlug: e.courseSlug,
      totalSeats: e.total,
      claimedSeats: e.claimed,
      unavailableSeats: e.unavailable,
    })
  );

  // Build coupon rows with redeemer email
  const couponRows: CouponRow[] = allCoupons.map((coupon) => {
    let redeemedByEmail: string | null = null;
    if (coupon.redeemedByUserId !== null) {
      const user = getUserById(coupon.redeemedByUserId);
      redeemedByEmail = user?.email ?? null;
    }
    const course = getCourseById(coupon.courseId);
    return {
      id: coupon.id,
      code: coupon.code,
      courseId: coupon.courseId,
      courseTitle: course?.title ?? "Unknown Course",
      redeemedByEmail,
      seatBlock: seatBlockFor(coupon),
      createdAt: coupon.createdAt,
    };
  });

  return { courseStats, couponRows };
}

function CopyButton({ code }: { code: string }) {
  const [copied, setCopied] = useState(false);

  function handleCopy() {
    const url = `${window.location.origin}/redeem/${code}`;
    navigator.clipboard.writeText(url).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    });
  }

  return (
    <button
      onClick={handleCopy}
      className="inline-flex items-center gap-1 rounded-md px-2 py-1 text-xs font-medium text-primary hover:bg-primary/10 transition-colors"
      title="Copy redemption link"
    >
      {copied ? (
        <>
          <Check className="size-3" />
          Copied
        </>
      ) : (
        <>
          <Copy className="size-3" />
          Copy link
        </>
      )}
    </button>
  );
}

export default function Team({ loaderData }: Route.ComponentProps) {
  const { courseStats, couponRows } = loaderData;
  const [courseFilter, setCourseFilter] = useState<number | "all">("all");

  const filteredCoupons =
    courseFilter === "all"
      ? couponRows
      : couponRows.filter((c) => c.courseId === courseFilter);

  return (
    <div className="mx-auto max-w-7xl p-6 lg:p-8">
      <nav className="mb-6 text-sm text-muted-foreground">
        <Link to="/" className="hover:text-foreground">
          Home
        </Link>
        <span className="mx-2">/</span>
        <span className="text-foreground">Team</span>
      </nav>

      <div className="mb-8">
        <h1 className="text-3xl font-bold">Team Management</h1>
        <p className="mt-1 text-muted-foreground">
          Manage your team&apos;s course seats and coupon codes
        </p>
      </div>

      {/* Per-course stats */}
      {courseStats.length > 0 && (
        <div className="mb-8 grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {courseStats.map((stat) => (
            <Card key={stat.courseId}>
              <CardHeader className="pb-2">
                <div className="flex items-center gap-2">
                  <BookOpen className="size-4 text-muted-foreground" />
                  <h3 className="font-semibold truncate">{stat.courseTitle}</h3>
                </div>
              </CardHeader>
              <CardContent>
                <div className="flex items-center justify-between">
                  {stat.totalSeats === 0 && stat.unavailableSeats > 0 ? (
                    // Every seat for this Course came from Refunded Purchases.
                    <div>
                      <p className="text-2xl font-bold">Refunded</p>
                      <p className="text-xs text-muted-foreground">
                        {stat.unavailableSeats === 1
                          ? "The 1 seat was refunded and is no longer available."
                          : `All ${stat.unavailableSeats} seats were refunded and are no longer available.`}
                      </p>
                    </div>
                  ) : (
                    <div>
                      <p className="text-2xl font-bold">
                        {stat.claimedSeats}
                        <span className="text-base font-normal text-muted-foreground">
                          {" "}
                          / {stat.totalSeats}
                        </span>
                      </p>
                      <p className="text-xs text-muted-foreground">
                        seats claimed
                      </p>
                      {stat.unavailableSeats > 0 && (
                        <p className="mt-1 text-xs text-muted-foreground">
                          {stat.unavailableSeats === 1
                            ? "Plus 1 refunded seat, no longer available."
                            : `Plus ${stat.unavailableSeats} refunded seats, no longer available.`}
                        </p>
                      )}
                    </div>
                  )}
                  <Link to={`/courses/${stat.courseSlug}/purchase?mode=team`}>
                    <Button variant="outline" size="sm">
                      Buy more seats
                    </Button>
                  </Link>
                </div>
              </CardContent>
            </Card>
          ))}
        </div>
      )}

      {/* Coupon list */}
      <div>
        <div className="mb-4 flex items-center justify-between">
          <h2 className="text-lg font-semibold">Coupons</h2>
          {courseStats.length > 1 && (
            <select
              value={courseFilter}
              onChange={(e) =>
                setCourseFilter(
                  e.target.value === "all" ? "all" : Number(e.target.value)
                )
              }
              className="rounded-md border border-input bg-background px-3 py-1.5 text-sm"
            >
              <option value="all">All courses</option>
              {courseStats.map((stat) => (
                <option key={stat.courseId} value={stat.courseId}>
                  {stat.courseTitle}
                </option>
              ))}
            </select>
          )}
        </div>

        {filteredCoupons.length === 0 ? (
          <p className="text-sm text-muted-foreground">No coupons yet.</p>
        ) : (
          <div className="overflow-x-auto rounded-md border">
            <table className="w-full text-sm">
              <thead>
                <tr className="border-b bg-muted/50">
                  <th className="px-4 py-3 text-left font-medium">Code</th>
                  <th className="px-4 py-3 text-left font-medium">Course</th>
                  <th className="px-4 py-3 text-left font-medium">Status</th>
                  <th className="px-4 py-3 text-left font-medium">Action</th>
                </tr>
              </thead>
              <tbody>
                {filteredCoupons.map((coupon) => (
                  <tr key={coupon.id} className="border-b last:border-0">
                    <td className="px-4 py-3">
                      <code className="rounded bg-muted px-2 py-0.5 text-xs">
                        {coupon.code}
                      </code>
                    </td>
                    <td className="px-4 py-3 text-muted-foreground">
                      {coupon.courseTitle}
                    </td>
                    <td className="px-4 py-3">
                      {coupon.redeemedByEmail ? (
                        <span className="text-muted-foreground">
                          Claimed by {coupon.redeemedByEmail}
                        </span>
                      ) : coupon.seatBlock ? (
                        <span
                          className={
                            coupon.seatBlock === "refunded"
                              ? "inline-flex items-center rounded-full bg-gray-100 px-2 py-0.5 text-xs font-medium text-gray-700 dark:bg-gray-800 dark:text-gray-300"
                              : "inline-flex items-center rounded-full bg-amber-100 px-2 py-0.5 text-xs font-medium text-amber-800 dark:bg-amber-900/30 dark:text-amber-300"
                          }
                          title={TEAM_SEAT_BLOCK_LABELS[coupon.seatBlock].detail}
                        >
                          {TEAM_SEAT_BLOCK_LABELS[coupon.seatBlock].label}
                        </span>
                      ) : (
                        <span className="inline-flex items-center rounded-full bg-green-100 px-2 py-0.5 text-xs font-medium text-green-700 dark:bg-green-900/30 dark:text-green-400">
                          Unclaimed
                        </span>
                      )}
                    </td>
                    <td className="px-4 py-3">
                      {!coupon.redeemedByEmail &&
                        (coupon.seatBlock ? (
                          <span className="text-xs text-muted-foreground">
                            {TEAM_SEAT_BLOCK_LABELS[coupon.seatBlock].detail}
                          </span>
                        ) : (
                          <CopyButton code={coupon.code} />
                        ))}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
}

export function ErrorBoundary({ error }: Route.ErrorBoundaryProps) {
  let title = "Something went wrong";
  let message = "An unexpected error occurred.";

  if (isRouteErrorResponse(error)) {
    if (error.status === 401) {
      title = "Sign in required";
      message =
        typeof error.data === "string"
          ? error.data
          : "Please select a user from the DevUI panel.";
    } else if (error.status === 403) {
      title = "No team found";
      message =
        typeof error.data === "string"
          ? error.data
          : "You don't have a team yet.";
    } else {
      title = `Error ${error.status}`;
      message = typeof error.data === "string" ? error.data : error.statusText;
    }
  }

  return (
    <div className="flex min-h-[50vh] items-center justify-center p-6">
      <div className="text-center">
        <AlertTriangle className="mx-auto mb-4 size-12 text-muted-foreground" />
        <h1 className="mb-2 text-2xl font-bold">{title}</h1>
        <p className="mb-6 text-muted-foreground">{message}</p>
        <div className="flex items-center justify-center gap-3">
          <Link to="/">
            <Button>Go Home</Button>
          </Link>
          <Link to="/courses">
            <Button variant="outline">Browse Courses</Button>
          </Link>
        </div>
      </div>
    </div>
  );
}
